const corpHeaders = (from: string, extra: Partial<RawHeaders> = {}): RawHeaders => ({
  from,
  replyTo: from.replace(/^.*</, '').replace(/>$/, ''),
  returnPath: `<${from.replace(/^.*</, '').replace(/>$/, '')}>`,
  spf: 'PASS',
  dkim: 'PASS',
  dmarc: 'PASS',
  ip: '10.20.0.15 (mx1.nordtech.ru)',
  received: 'from mx1.nordtech.ru (10.20.0.15) by exch01.nordtech.ru',
  messageId: `<${Math.random().toString(36).slice(2, 10)}@exch01.nordtech.ru>`,
  ...extra,
});

const link = (id: string, r: SandboxLinkReport) => ({ id, ...r });
const file = (id: string, r: SandboxFileReport) => ({ id, ...r });

const corpLink = (id: string, text: string, url: string, notes: string) =>
  link(id, {
    displayText: text,
    shownUrl: url,
    realUrl: url,
    redirectChain: [url],
    domain: new URL(url).hostname,
    domainAge: '9 лет (2017)',
    domainAgeDays: 3300,
    registrar: 'RU-CENTER',
    ssl: 'Валиден · выдан для *.nordtech.ru',
    verdict: 'clean',
    notes,
  });

